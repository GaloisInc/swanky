/*! Cryptographic primitives used for VOLE-it-HEAD */
use crate::parameters::{
    Chall1Bytes, Chall2Bytes, ComBytes, FLambda, H3Bytes, Params, Prng, SecurityParamBytes, Xof,
};
use crate::vole::commit_reconstruct::Corrections;
use hybrid_array::Array;
use rand::{Rng, TryRng, rand_core::Infallible};
use sha3::digest::{ExtendableOutput, Update, XofReader};
use swanky_serialization::CanonicalSerialize;

/// Initialization Vector.
pub(crate) type IV = [u8; 16];
/// Key as found in the internal nodes of the Tree-PRG/GGM-tree.
pub(crate) type Key<P> = Array<u8, SecurityParamBytes<P>>;
/// Commitment as generated by 1-VC.
pub(crate) type Com<P> = Array<u8, ComBytes<P>>;
/// Seed generated by 1-VC.
pub(crate) type Seed<P> = Array<u8, SecurityParamBytes<P>>;

/// The PRG used by VOLE-in-the-Head.
///
/// This is a thin wrapper around [`SwankyRng`], which itself implements a
/// AES-CTR-based PRG as defined in the FAEST spec.
pub(crate) struct Prg<P: Params>(Prng<P>);

impl<P: Params> Prg<P> {
    /// Create a new [`Prg`] using the provided [`Seed`] and [`IV`].
    pub(crate) fn new(seed: Seed<P>, iv: IV) -> Self {
        Self(P::new_prng_with_iv(&seed, iv))
    }

    /// Create a new [`Prg`] using the provided [`Seed`].
    pub(crate) fn new_no_iv(seed: Seed<P>) -> Self {
        Self(P::new_prng(&seed))
    }
}

impl<P: Params> TryRng for Prg<P> {
    type Error = Infallible;

    fn try_next_u32(&mut self) -> Result<u32, Self::Error> {
        Ok(self.0.next_u32())
    }

    fn try_next_u64(&mut self) -> Result<u64, Self::Error> {
        Ok(self.0.next_u64())
    }

    fn try_fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), Self::Error> {
        self.0.try_fill_bytes(dest)
    }
}

#[cfg(test)]
mod tests {
    use crate::parameters::{Binary128Bit, Binary256Bit};

    macro_rules! make_tests {
        (mod $name:ident { params = $params:ty $(,)? }) => {
            mod $name {
                use super::*;

                #[allow(dead_code)]
                type P = $params;

                use super::super::{IV, Params, Seed};
                use rand::RngExt;
                use swanky_field_binary::F2;

                #[test]
                fn swanky_prg_matches_stream_bits() {
                    let seed: Seed<P> = Seed::<P>::from_fn(|_| 5u8);
                    let iv: IV = [11u8; 16];

                    let lengths = [
                        1, 7, 8, 63, 64, 65, 127, 128, 129, 511, 512, 513, 1023, 1024, 1025, 2047,
                        2048, 2049, 100000, 1048575, 1048576, 1048577,
                    ];
                    for &l in &lengths {
                        let mut rng = P::new_prng_with_iv(&seed, iv);
                        let randoms = (0..l / 64 + 1)
                            .map(|_| rng.random::<u64>())
                            .collect::<Vec<_>>();
                        let mut expected_bits = Vec::with_capacity(l);
                        for block in randoms {
                            for i in 0..64 {
                                let bit = ((block >> i) & 1) == 1;
                                expected_bits.push(F2::from(bit));
                            }
                        }
                        expected_bits.truncate(l);
                        let mut stream = P::new_prng_with_iv(&seed, iv);
                        let mut stream_bits = Vec::with_capacity(l);
                        while stream_bits.len() < l {
                            let block = stream.random::<u64>();
                            for i in 0..64 {
                                if stream_bits.len() == l {
                                    break;
                                }
                                let bit = ((block >> i) & 1) == 1;
                                stream_bits.push(F2::from(bit));
                            }
                        }
                        assert_eq!(expected_bits, stream_bits, "bit mismatch for l={}", l);
                    }
                }
            }
        };
    }

    make_tests! { mod binary_128_bit { params = Binary128Bit } }
    make_tests! { mod binary_256_bit { params = Binary256Bit } }
}

fn hash<P: Params>(bytes: &[u8], domain_seperator: u8, output: &mut [u8]) {
    let mut hasher = Xof::<P>::default();
    hasher.update(bytes);
    hasher.update(&[domain_seperator]);
    hasher.finalize_xof_into(output);
}

/// Hash function that generates a [`Seed`] and a [`Com`]mitment from a [`Key`] and an initialization vector [`IV`].
///
/// This function is applied on the leaves keys of the Tree-PRG/GGM-tree to generate the seeds and commitments.
/// This function corresponds to the H0 in the FAEST spec, defined page 16.
pub(crate) fn h0<P: Params>(x: Key<P>, iv: IV) -> (Seed<P>, Com<P>) {
    // Hash x||iv to generate the Key
    let mut hasher = Xof::<P>::default();
    hasher.update(&x);
    hasher.update(&iv);
    hasher.update(&[0u8]);

    let mut reader = hasher.finalize_xof();
    let mut seed = Seed::<P>::default();
    let mut commitment = Com::<P>::default();
    reader.read(seed.as_mut_slice());
    reader.read(commitment.as_mut_slice());

    (seed, commitment)
}

/// Hash digest for a collision-resistant hash function.
///
/// This is used for various purposes throughout the protocol.
#[derive(Clone, Default)]
pub(crate) struct H1<P: Params>(Array<u8, ComBytes<P>>);

impl<P: Params> H1<P> {
    /// Compute the [`H1`] hash from a slice of bytes.
    pub(crate) fn hash(bytes: &[u8]) -> Self {
        let mut out = Self::default();
        hash::<P>(bytes, 1, &mut out.0);
        out
    }

    /// Hash a sequence of commitments, returning the resulting hash.
    ///
    /// This function is applied to the leaves commitments of the
    /// Tree-PRG/GGM-tree, and corresponds to the H1 function in the FAEST spec,
    /// defined on page 16.
    pub(crate) fn hash_commitments(commitments: &[Com<P>]) -> Self {
        let bytes = commitments
            .iter()
            .flat_map(|com| com.iter().copied())
            .collect::<Vec<_>>();
        Self::hash(&bytes)
    }
}

impl<P: Params> From<H1<P>> for Com<P> {
    fn from(value: H1<P>) -> Self {
        value.0
    }
}

impl<P: Params> AsRef<Array<u8, ComBytes<P>>> for H1<P> {
    fn as_ref(&self) -> &Array<u8, ComBytes<P>> {
        &self.0
    }
}

/// Hash function for the Fiat-Shamir challenges generated in the protocol.
///
/// This is `$H_2^j$` in FAEST spec
#[derive(Default)]
struct H2Hasher<P: Params>(Xof<P>);

impl<P: Params> H2Hasher<P> {
    fn update(&mut self, data: &[u8]) {
        self.0.update(data);
    }

    fn finalize(mut self, out: &mut [u8]) {
        self.0.update(&[2u8]);
        self.0.finalize_xof_into(out);
    }
}

/// First challenge
pub(crate) type Chall1<P> = Array<u8, Chall1Bytes<P>>;

/// Make the first Fiat-Shamir challenge.
///
/// This computes `$H_2^1$` in FAEST spec.
pub(crate) fn h2_chall1<P: Params>(
    mu: &H1<P>,
    hcom: &Com<P>,
    corrections: &Corrections<P>,
    iv: &IV,
) -> Chall1<P> {
    let mut hasher = H2Hasher::<P>::default();

    hasher.update(&mu.0);
    hasher.update(hcom);
    hasher.update(&corrections.to_bytes());
    hasher.update(iv);

    let mut out = Chall1::<P>::default();
    hasher.finalize(&mut out);
    out
}

/// Second challenge
pub(crate) type Chall2<P> = Array<u8, Chall2Bytes<P>>;

/// This is `$H_2^2$` in FAEST spec.
#[allow(unused)]
pub(crate) fn h_chall2<P: Params>(inp: &[u8]) -> Chall2<P> {
    let mut hasher = H2Hasher::<P>::default();

    hasher.update(inp);

    let mut out = Chall2::<P>::default();
    hasher.finalize(&mut out);
    out
}

/// Third challenge.
pub(crate) type Chall3<P> = Array<u8, SecurityParamBytes<P>>;

/// Makes the third Fiat-Shamir challenge.
///
/// This computes `$H_2^3$` in FAEST spec.
#[allow(unused)]
pub(crate) fn h2_chall3<P: Params>(
    chall2: &Chall2<P>,
    a_tilde: &FLambda<P>,
    b_tilde: &FLambda<P>,
) -> Chall3<P> {
    let mut hasher = H2Hasher::<P>::default();

    hasher.update(chall2);
    hasher.update(&a_tilde.to_bytes());
    hasher.update(&b_tilde.to_bytes());

    let mut out = Chall3::<P>::default();
    hasher.finalize(&mut out);
    out
}

/// Hash digest for randomness and IV generation.
///
/// This should incorporate secret information or randomness (e.g. that only
/// the verifier knows), to derive secret, per-proof values.
#[derive(Clone, Default)]
pub(crate) struct H3<P: Params>(Array<u8, H3Bytes<P>>);

impl<P: Params> H3<P> {
    /// Compute the [`H3`] hash from a slice of bytes.
    #[allow(unused)]
    pub(crate) fn hash(bytes: &[u8]) -> Self {
        let mut out = Self::default();
        hash::<P>(bytes, 3, &mut out.0);
        out
    }

    /// Derive the [`H3`] hash from an instance of [`Xof`], which we assume
    /// has already been updated with all relevant secret information.
    pub(crate) fn from_xof(mut xof: Xof<P>) -> Self {
        let mut out = Self::default();
        // Append 0x3 for domain separation
        xof.update(&[3u8]);
        xof.finalize_xof_into(&mut out.0);
        out
    }
}

impl<P: Params> AsRef<Array<u8, H3Bytes<P>>> for H3<P> {
    fn as_ref(&self) -> &Array<u8, H3Bytes<P>> {
        &self.0
    }
}
